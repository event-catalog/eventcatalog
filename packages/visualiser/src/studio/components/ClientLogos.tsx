/**
 * The logo of the company behind an agent, from the name it joined with (agentName on the MCP tools, e.g. "Claude
 * Code", "Codex", "Cursor"), when it's one we know: shown instead of a robot on its avatar, pointer and comments
 */
export const agentLogoFor = (name?: string) => {
  const lowered = (name ?? "").toLowerCase();
  if (lowered.includes("claude code")) return ClaudeCodeLogo;
  if (/\b(claude|anthropic)\b/.test(lowered)) return ClaudeLogo;
  if (/\b(codex|chatgpt|openai|gpt)/.test(lowered)) return OpenAILogo;
  if (/\bcursor\b/.test(lowered)) return CursorLogo;
  return undefined;
};

/** An agent's mark: its company's logo when it's one we know (agentLogoFor), else a robot */
export function AgentMark({
  name,
  size = 14,
}: {
  name?: string;
  size?: number;
}) {
  const Logo = agentLogoFor(name);
  // On a light disc, so the logo keeps its colours on the agent's coloured avatar or label
  return Logo ? (
    <span
      className="flex flex-none items-center justify-center rounded-full bg-white"
      style={{ width: size + 4, height: size + 4, color: "#111827" }}
    >
      <Logo width={size - 2} height={size - 2} />
    </span>
  ) : (
    <Bot size={size} />
  );
}
